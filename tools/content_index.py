#!/usr/bin/env python3
"""Validate content items and regenerate content/registry.md.

Usage: python3 tools/content_index.py   (exit code 1 on validation errors)
"""
import pathlib, re, sys, datetime

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
REQUIRED = ["id", "format", "topic", "segments", "pillar", "objective", "hypothesis", "title", "hook",
            "production_status", "approval_status", "publish_date", "created", "updated"]
PROD = {"IDEA", "RESEARCHED", "SCRIPTED", "VOICED", "EDITED", "PACKAGED", "PUBLISHED", "KILLED"}
APPR = {"DRAFT", "PROPOSED", "APPROVED", "REJECTED"}
PATTERN = {"shorts": re.compile(r"^SWAI-S\d{3}$"), "long": re.compile(r"^SWAI-L\d{3}$")}


def front_matter(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return None
    data = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith(" "):
            k, v = line.split(":", 1)
            data[k.strip()] = v.strip().strip('"')
    return data


def main():
    errors, rows, seen = [], [], {}
    for folder in ("shorts", "long"):
        for path in sorted((CONTENT / folder).glob("*.md")):
            rel = path.relative_to(ROOT)
            fm = front_matter(path)
            if fm is None:
                errors.append(f"{rel}: missing front matter")
                continue
            for k in REQUIRED:
                if k not in fm:
                    errors.append(f"{rel}: missing field '{k}'")
            cid = fm.get("id", "")
            if not PATTERN[folder].match(cid):
                errors.append(f"{rel}: id '{cid}' invalid for {folder}/")
            if not path.name.startswith(cid + "-"):
                errors.append(f"{rel}: file name must start with '{cid}-'")
            if cid in seen:
                errors.append(f"{rel}: duplicate id {cid} (also {seen[cid]})")
            seen[cid] = rel
            if fm.get("production_status") not in PROD:
                errors.append(f"{rel}: bad production_status '{fm.get('production_status')}'")
            if fm.get("approval_status") not in APPR:
                errors.append(f"{rel}: bad approval_status '{fm.get('approval_status')}'")
            if fm.get("production_status") == "PUBLISHED" and fm.get("approval_status") != "APPROVED":
                errors.append(f"{rel}: PUBLISHED without APPROVED")
            rows.append((cid, fm, rel))

    def next_id(prefix):
        nums = [int(c[-3:]) for c, _, _ in rows if c.startswith(prefix)]
        return f"{prefix}{(max(nums) + 1) if nums else 1:03d}"

    out = ["# Content registry", "",
           "_Generated by `python3 tools/content_index.py`. Do not edit by hand._", "",
           f"Next free IDs: **{next_id('SWAI-S')}** (Short) · **{next_id('SWAI-L')}** (long-form)", "",
           "| ID | Title | Pillar | Segments | Production | Approval | Publish date | File |",
           "|---|---|---|---|---|---|---|---|"]
    for cid, fm, rel in sorted(rows):
        out.append(f"| {cid} | {fm.get('title','')} | {fm.get('pillar','')} | {fm.get('segments','')} | "
                   f"{fm.get('production_status','')} | {fm.get('approval_status','')} | {fm.get('publish_date','')} | `{rel}` |")
    if not rows:
        out.append("| — | _No content items yet_ | | | | | | |")
    (CONTENT / "registry.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    for e in errors:
        print("ERROR:", e)
    print(f"{len(rows)} items, {len(errors)} errors. Registry written.")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
